// genmenu 讀菜單的 CSV，產生一個 Go 原始檔。由 menu.go 裡的 //go:generate 執行：
//
//	go generate ./chapters/32-toolchain
package main

import (
	"bytes"
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	in := flag.String("in", "menu.csv", "菜單的 CSV 檔")
	out := flag.String("out", "menu_gen.go", "要產生的 Go 檔")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genmenu:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	f, err := os.Open(in)
	if err != nil {
		return err
	}
	defer f.Close()
	src, err := generate(f, filepath.Base(in))
	if err != nil {
		return fmt.Errorf("%s：%w", in, err)
	}
	return os.WriteFile(out, src, 0o644)
}

// generate 把「菜名,價格」的 CSV 轉成 Go 原始碼，最後用 go/format 排版。
// 第一行是標題，跳過。
func generate(r io.Reader, source string) ([]byte, error) {
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		return nil, err
	}
	if len(rows) < 2 {
		return nil, errors.New("菜單是空的")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genmenu from %s; DO NOT EDIT.\n\n", source)
	b.WriteString("package main\n\nvar menu = []dish{\n")
	for i, row := range rows[1:] {
		price, err := strconv.Atoi(row[1])
		if err != nil {
			return nil, fmt.Errorf("第 %d 行的價格：%w", i+2, err)
		}
		fmt.Fprintf(&b, "{%q, %d},\n", row[0], price)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
